export const PO_FREQUENCIES = ['daily', 'weekly', 'monthly']

const QTY_MULTIPLIERS = { daily: 1, weekly: 4, monthly: 12 }

export function getDefaultProcurementSettings() {
  return {
    autoGenerate: true,
    nearThresholdPercent: 0.2,
    lastAutoGenerated: null,
  }
}

export function getItemStock(item) {
  return item.stock ?? item.currentStock ?? 0
}

export function getItemMinimum(item) {
  return item.minimum ?? item.minimumStock ?? 0
}

export function isLowOrNearThreshold(item, nearPercent = 0.2) {
  const stock = getItemStock(item)
  const minimum = getItemMinimum(item)
  if (minimum <= 0) return stock <= 0
  return stock <= minimum * (1 + nearPercent)
}

export function isCriticalLow(item) {
  const stock = getItemStock(item)
  const minimum = getItemMinimum(item)
  if (stock === 0) return true
  if (minimum <= 0) return false
  return stock <= minimum * 0.5
}

export function isLowStock(item) {
  const stock = getItemStock(item)
  const minimum = getItemMinimum(item)
  return stock > 0 && stock <= minimum
}

export function buildPOItemFromInventory(inv, frequency) {
  const stock = getItemStock(inv)
  const minimum = getItemMinimum(inv)
  const deficit = Math.max(0, minimum - stock)
  const baseQty = Math.max(deficit, minimum * 0.5, 1)
  const requiredQty = Math.ceil(baseQty * QTY_MULTIPLIERS[frequency] * 10) / 10
  const cost = inv.cost ?? inv.unitCost ?? 0
  return {
    inventoryId: inv.id,
    name: inv.name,
    sku: inv.sku || '',
    currentStock: stock,
    minimum,
    deficit,
    requiredQty,
    unit: inv.unit || inv.baseUnit || 'kg',
    cost,
    estimatedCost: cost * requiredQty,
  }
}

export function scalePOItem(item, targetFrequency) {
  const sourceQty = item.requiredQty || item.requiredQuantity || 1
  const dailyBase = sourceQty / (QTY_MULTIPLIERS[item._sourceFrequency || 'daily'] || 1)
  const requiredQty = Math.ceil(dailyBase * QTY_MULTIPLIERS[targetFrequency] * 10) / 10
  const cost = item.cost || 0
  return {
    inventoryId: item.inventoryId,
    name: item.name,
    sku: item.sku || '',
    currentStock: item.currentStock,
    minimum: item.minimum ?? item.minimumStock,
    deficit: item.deficit ?? Math.max(0, (item.minimum ?? 0) - (item.currentStock ?? 0)),
    requiredQty,
    unit: item.unit || 'kg',
    cost,
    estimatedCost: cost * requiredQty,
  }
}

export function buildGroupId(restaurantId) {
  const today = new Date().toISOString().slice(0, 10)
  return `pg-${restaurantId}-${today}`
}

export function poNumberFor(frequency, seq) {
  const prefix = { daily: 'D', weekly: 'W', monthly: 'M' }[frequency] || 'X'
  return `PO-${prefix}-${seq}`
}

export function getLowStockItems(inventory, restaurantId, nearPercent = 0.2) {
  return inventory.filter(
    (item) => item.restaurantId === restaurantId && isLowOrNearThreshold(item, nearPercent),
  )
}

export function autoGeneratePOGroup({
  inventory,
  restaurantId,
  existingPOs = [],
  nearPercent = 0.2,
  groupId = buildGroupId(restaurantId),
}) {
  const lowItems = getLowStockItems(inventory, restaurantId, nearPercent)
  if (!lowItems.length) return existingPOs

  const activeStatuses = ['Draft', 'Pending']
  const existingGroup = existingPOs.filter(
    (po) => po.restaurantId === restaurantId && po.groupId === groupId && activeStatuses.includes(po.status),
  )

  const today = new Date().toISOString().slice(0, 10)
  const seq = existingPOs.filter((po) => po.restaurantId === restaurantId).length + 1
  let updated = [...existingPOs]

  PO_FREQUENCIES.forEach((frequency, idx) => {
    const existing = existingGroup.find((po) => po.frequency === frequency)
    const items = lowItems.map((inv) => buildPOItemFromInventory(inv, frequency))

    if (existing) {
      updated = updated.map((po) => {
        if (po.id !== existing.id) return po
        const mergedItems = mergePOItems(po.items || [], items)
        return {
          ...po,
          items: mergedItems,
          updatedAt: new Date().toISOString(),
          autoGenerated: true,
        }
      })
    } else {
      const newPo = {
        id: `po${Date.now().toString(36)}${idx}`,
        restaurantId,
        groupId,
        frequency,
        number: poNumberFor(frequency, seq + idx),
        title: `${frequency.charAt(0).toUpperCase() + frequency.slice(1)} Auto PO — ${today}`,
        status: 'Draft',
        supplier: 'Auto-generated',
        items,
        generatedAt: today,
        autoGenerated: true,
        createdAt: new Date().toISOString(),
      }
      updated = [newPo, ...updated]
    }
  })

  return updated
}

function mergePOItems(existing, suggested) {
  const existingMap = new Map((existing || []).map((item) => [item.inventoryId, item]))
  const suggestedIds = new Set(suggested.map((item) => item.inventoryId))

  const kept = (existing || []).filter((item) => suggestedIds.has(item.inventoryId))
  const keptIds = new Set(kept.map((item) => item.inventoryId))

  const added = suggested.filter((item) => !keptIds.has(item.inventoryId))
  return [...kept, ...added]
}

export function syncPOGroupFromSource(purchaseOrders, sourcePoId, newItems) {
  const source = purchaseOrders.find((po) => po.id === sourcePoId)
  if (!source?.groupId) {
    return purchaseOrders.map((po) => (po.id === sourcePoId ? { ...po, items: newItems, updatedAt: new Date().toISOString() } : po))
  }

  const closedStatuses = ['Completed', 'Received']
  const siblings = purchaseOrders.filter(
    (po) => po.groupId === source.groupId && po.id !== sourcePoId && !closedStatuses.includes(po.status),
  )

  return purchaseOrders.map((po) => {
    if (po.id === sourcePoId) {
      return { ...po, items: newItems, updatedAt: new Date().toISOString(), manuallyEdited: true }
    }
    if (!siblings.find((s) => s.id === po.id)) return po

    const syncedItems = newItems.map((item) => scalePOItem({ ...item, _sourceFrequency: source.frequency }, po.frequency))
    return {
      ...po,
      items: syncedItems,
      lastSyncedFrom: sourcePoId,
      updatedAt: new Date().toISOString(),
    }
  })
}

export function removeItemsFromSiblingPOs(purchaseOrders, groupId, sourcePoId, inventoryIds) {
  const idSet = new Set(inventoryIds)
  return purchaseOrders.map((po) => {
    if (po.groupId !== groupId || po.id === sourcePoId) return po
    return {
      ...po,
      items: (po.items || []).filter((item) => !idSet.has(item.inventoryId)),
      updatedAt: new Date().toISOString(),
    }
  })
}

export function calcPOTotal(po) {
  return (po.items || []).reduce((sum, item) => {
    const qty = item.requiredQty ?? item.requiredQuantity ?? 0
    return sum + (item.cost || 0) * qty
  }, 0)
}

export function buildLowStockNotificationEntries(inventory, restaurantId, existingNotifications = []) {
  const restaurantInventory = inventory.filter((item) => item.restaurantId === restaurantId)
  const critical = restaurantInventory.filter(isCriticalLow)
  const low = restaurantInventory.filter(isLowStock)
  const entries = []
  const recentKeys = new Set(
    existingNotifications
      .filter((n) => n.restaurantId === restaurantId && n.source === 'inventory')
      .map((n) => n.sourceKey),
  )

  critical.forEach((item) => {
    const key = `critical-${item.id}`
    if (recentKeys.has(key)) return
    entries.push({
      id: `n${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`,
      restaurantId,
      title: 'Critical low stock',
      message: `${item.name} is critically low (${getItemStock(item)} ${item.unit || item.baseUnit || ''} remaining). Reorder immediately.`,
      time: 'Just now',
      read: false,
      type: 'warning',
      priority: 'critical',
      source: 'inventory',
      sourceKey: key,
      inventoryId: item.id,
      createdAt: new Date().toISOString(),
    })
  })

  low.forEach((item) => {
    const key = `low-${item.id}`
    if (recentKeys.has(key)) return
    entries.push({
      id: `n${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`,
      restaurantId,
      title: 'Low stock alert',
      message: `${item.name} is below minimum (${getItemStock(item)}/${getItemMinimum(item)} ${item.unit || item.baseUnit || ''}).`,
      time: 'Just now',
      read: false,
      type: 'warning',
      priority: 'normal',
      source: 'inventory',
      sourceKey: key,
      inventoryId: item.id,
      createdAt: new Date().toISOString(),
    })
  })

  return entries
}


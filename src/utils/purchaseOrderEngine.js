export function parseInventoryUpload(text, inventory, restaurantId) {
  const lines = text.trim().split(/\r?\n/).filter(Boolean)
  const restaurantInventory = inventory.filter((item) => item.restaurantId === restaurantId)
  const results = { updated: [], created: [], notFound: [], errors: [], skipped: [] }

  const isHeader = (line) => /^sku/i.test(line) || /new stock/i.test(line)
  const parseCsvLine = (line) => {
    const cells = []
    let current = ''
    let inQuotes = false
    for (let i = 0; i < line.length; i += 1) {
      const ch = line[i]
      if (ch === '"') {
        inQuotes = !inQuotes
        continue
      }
      if (ch === ',' && !inQuotes) {
        cells.push(current.trim())
        current = ''
        continue
      }
      current += ch
    }
    cells.push(current.trim())
    return cells
  }

  const findMatch = (parts, skuKey, nameKey) => restaurantInventory.find(
    (item) => (skuKey && (item.sku?.toLowerCase() === skuKey || item.id.toLowerCase() === skuKey))
      || (nameKey && item.name.toLowerCase() === nameKey),
  )

  const startIndex = lines.length && isHeader(lines[0]) ? 1 : 0
  const pendingSkus = new Set()

  lines.slice(startIndex).forEach((line, index) => {
    const lineNum = startIndex + index + 1
    const parts = parseCsvLine(line)
    if (!parts.length) return

    let match = null
    let qty = null
    let sku = ''
    let name = ''
    let unit = 'kg'
    let minimum = 5
    let category = 'General'

    if (parts.length >= 5) {
      sku = parts[0] || ''
      name = (parts[1] || '').replace(/^"|"$/g, '')
      unit = parts[2] || 'kg'
      const newStock = parts[4]
      minimum = Number(parts[5]) || 5
      category = parts[6]?.trim() || 'General'
      if (!newStock || newStock.trim() === '') {
        results.skipped.push({ line: lineNum, identifier: sku || name })
        return
      }
      qty = Number(newStock)
      match = findMatch(parts, sku?.toLowerCase(), name.toLowerCase())
    } else {
      qty = Number(parts[parts.length - 1])
      const identifier = parts.slice(0, -1).join(' ').toLowerCase()
      match = restaurantInventory.find(
        (item) => item.name.toLowerCase() === identifier
          || item.sku?.toLowerCase() === identifier
          || item.id.toLowerCase() === identifier,
      )
      name = parts.slice(0, -1).join(', ')
    }

    if (qty === null || Number.isNaN(qty) || qty < 0) {
      results.errors.push({ line: lineNum, text: line, reason: 'Invalid or missing quantity' })
      return
    }

    if (!match) {
      if (!name?.trim()) {
        results.notFound.push({ line: lineNum, identifier: sku || parts[0] || 'Unknown' })
        return
      }
      const skuKey = sku?.toLowerCase()
      const skuTaken = skuKey && (
        restaurantInventory.some((item) => item.sku?.toLowerCase() === skuKey || item.id.toLowerCase() === skuKey)
        || pendingSkus.has(skuKey)
      )
      if (skuTaken) {
        results.errors.push({ line: lineNum, text: line, reason: `SKU "${sku}" already exists` })
        return
      }
      if (skuKey) pendingSkus.add(skuKey)
      results.created.push({
        line: lineNum,
        sku: sku?.trim() || `INV-${Date.now().toString(36).slice(-5).toUpperCase()}-${index}`,
        name: name.trim(),
        unit: unit || 'kg',
        quantity: qty,
        minimum,
        category,
      })
      return
    }

    results.updated.push({ inventoryId: match.id, name: match.name, quantity: qty, previousStock: getItemStock(match) })
  })

  return results
}

export function buildInventoryUploadTemplate(inventory, restaurantId) {
  const items = inventory.filter((item) => item.restaurantId === restaurantId)
  const escape = (value) => `"${String(value ?? '').replace(/"/g, '""')}"`
  const header = 'SKU,Product Name,Unit,Current Stock,New Stock,Minimum,Category'
  const rows = items.map((item) => {
    const stock = getItemStock(item)
    const unit = item.unit || item.baseUnit || 'kg'
    return [
      item.sku || item.id,
      escape(item.name),
      unit,
      stock,
      '',
      item.minimum ?? item.minimumStock ?? 5,
      item.category || 'General',
    ].join(',')
  })
  const blankRows = [
    ',,,,,,',
    'NEW-001,"New Product Name",kg,0,,5,General',
    'NEW-002,"Another Product",pcs,0,,10,General',
  ]
  return [header, ...rows, ...blankRows].join('\n')
}

export function downloadInventoryUploadTemplate(inventory, restaurantId, filename = 'stock-upload-template') {
  const csv = buildInventoryUploadTemplate(inventory, restaurantId)
  const blob = new Blob(['\uFEFF', csv], { type: 'text/csv;charset=utf-8;' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = `${filename}.csv`
  link.click()
  URL.revokeObjectURL(url)
}
